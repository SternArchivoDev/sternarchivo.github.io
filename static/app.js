(function () {
  "use strict";

  // ---------- DOM refs ----------
  const pkgSelect = document.getElementById("pkgManager");
  const chkNoComments = document.getElementById("chkNoComments");
  const chkArchive = document.getElementById("chkArchive");
  const generateBtn = document.getElementById("generateBtn");
  const downloadZipBtn = document.getElementById("downloadZipBtn");
  const fileListEl = document.getElementById("fileList");
  const fileContentEl = document.getElementById("fileContent");
  const statusMsg = document.getElementById("statusMessage");

  // ---------- Stato ----------
  let currentFiles = null;
  let currentSelectedPath = null;

  // ---------- Utility UI ----------
  function showStatus(msg, type = "info") {
    statusMsg.textContent = msg;
    statusMsg.className = `alert alert-${type}`;
    statusMsg.classList.remove("d-none");
  }

  function hideStatus() {
    statusMsg.classList.add("d-none");
  }

  function setLoading(loading) {
    generateBtn.disabled = loading;
    generateBtn.innerHTML = loading
      ? '<span class="spinner-border spinner-border-sm me-1"></span> Generazione...'
      : "🚀 Genera";
  }

  // ---------- Snippets per i package manager (Packer rimosso) ----------
  const SNIPPETS = {
    lazy: {
      // Versione commentata (template con commenti)
      commented: `-- [[ Bootstrap Lazy.nvim ]]
-- local lazypath = vim.fn.stdpath("data") .. "/lazy/lazy.nvim"
-- if not vim.loop.fs_stat(lazypath) then
--   vim.fn.system({
--     "git", "clone", "--filter=blob:none",
--     "https://github.com/folke/lazy.nvim.git",
--     "--branch=stable", lazypath
--   })
-- end
-- vim.opt.rtp:prepend(lazypath)
--
-- require("lazy").setup({
--   { import = "plugins" },
-- })`,
      // Versione attiva (senza commenti)
      active: `local lazypath = vim.fn.stdpath("data") .. "/lazy/lazy.nvim"
if not vim.loop.fs_stat(lazypath) then
  vim.fn.system({
    "git", "clone", "--filter=blob:none",
    "https://github.com/folke/lazy.nvim.git",
    "--branch=stable", lazypath
  })
end
vim.opt.rtp:prepend(lazypath)

require("lazy").setup({
  { import = "plugins" },
})`,
    },
    minimal: {
      commented: "-- [[ Minimal plugin manager: just a placeholder ]]",
      active: "-- Minimal plugin manager: just a placeholder",
    },
    other: {
      commented:
        "-- [[ Add your plugin manager bootstrap or manual plugin loading here. ]]",
      active:
        "-- Add your plugin manager bootstrap or manual plugin loading here.",
    },
  };

  function getSnippet(pkg, noComments) {
    const pkgData = SNIPPETS[pkg] || SNIPPETS.other;
    return noComments ? pkgData.active : pkgData.commented;
  }

  // ---------- Opzioni di base ----------
  function getBasicOpts(noComments) {
    const opts = `vim.opt.number = true
vim.opt.relativenumber = true
vim.opt.tabstop = 4
vim.opt.shiftwidth = 4
vim.opt.expandtab = true`;
    return noComments
      ? opts
      : `-- Uncomment and adjust the options you need:\n-- ${opts.replace(/\n/g, "\n-- ")}`;
  }

  // ---------- Modulo utente ----------
  function getUserContent(noComments) {
    if (noComments) {
      return `-- User-specific module
local M = {}
function M.setup()
  -- Add your custom code here (options, keymaps, autocmds, ...)
end
return M`;
    } else {
      return `-- User-specific module
-- This file is loaded after Lazy and plugins.
-- Put your personal settings here (options, keymaps, autocmds, etc.)
-- Example:
-- vim.opt.number = true
-- vim.keymap.set('n', '<leader>w', ':write<CR>')`;
    }
  }

  // ---------- Definizione dei template dei file (struttura moderna per Lazy) ----------
  const fileTemplates = [
    {
      path: "init.lua",
      content: (opts) => {
        const { pkg, noComments, genDate, pkgName } = opts;
        return `-- Generated by StitchVim on ${genDate}
print("Neovim configuration loaded (StitchVim v0.0.2)")

${getSnippet(pkg, noComments)}

-- Load user configuration (options, keymaps, autocmds)
require("user")

-- Put the rest of your configuration here (if any)
`;
      },
    },
    {
      path: "lua/user/init.lua",
      content: (opts) => getUserContent(opts.noComments),
    },
    {
      path: "lua/plugins/example.lua",
      content: (opts) => {
        // File di esempio per un plugin (commentato)
        return `-- Example plugin configuration
-- Add your plugins in this folder. Each file should return a table
-- that will be passed to Lazy.nvim.
--
-- return {
--   "catppuccin/nvim",
--   name = "catppuccin",
--   opts = {
--     flavour = "mocha", -- latte, frappe, macchiato, mocha
--   },
-- }
`;
      },
    },
    {
      path: "README.md",
      content: (opts) => {
        const { pkgName } = opts;
        return `# Neovim Configuration

Generated with StitchVim.

## Structure
- \`init.lua\` – entry point, bootstraps Lazy.nvim (if selected) and loads modules.
- \`lua/user/\` – your personal settings (options, keymaps, autocmds).
- \`lua/plugins/\` – place your plugin configuration files here.
  Each file should return a table compatible with Lazy.nvim.
  They will be automatically imported.

## Usage with Lazy.nvim
1. Add your plugin files in \`lua/plugins/\`.
2. Edit \`lua/user/init.lua\` to customize Neovim.
3. Start Neovim – Lazy will install plugins automatically.

For more info, see: https://github.com/folke/lazy.nvim
`;
      },
    },
  ];

  // ---------- Generazione ----------
  function generateConfig() {
    hideStatus();
    setLoading(true);

    try {
      const pkg = pkgSelect.value;
      const noComments = chkNoComments.checked;
      const genDate = new Date().toISOString().replace("T", " ").slice(0, 19);
      const pkgName = pkg.charAt(0).toUpperCase() + pkg.slice(1);

      const opts = { pkg, noComments, genDate, pkgName };

      const files = {};
      fileTemplates.forEach((tmpl) => {
        files[tmpl.path] = tmpl.content(opts);
      });

      currentFiles = files;
      renderFileList(files);
      const paths = Object.keys(files).sort();
      if (paths.length > 0) {
        selectFile(paths[0]);
      }
      showStatus(`✅ Generati ${Object.keys(files).length} file`, "success");
      downloadZipBtn.disabled = false;
    } catch (err) {
      showStatus(`❌ Errore: ${err.message}`, "danger");
    }

    setLoading(false);
  }

  // ---------- Render lista file ----------
  function renderFileList(files) {
    const paths = Object.keys(files).sort();
    if (paths.length === 0) {
      fileListEl.innerHTML = `<div class="list-group-item bg-dark text-secondary text-center">Nessun file</div>`;
      return;
    }
    let html = "";
    paths.forEach((path) => {
      const isActive = path === currentSelectedPath ? "active" : "";
      let icon = "📄";
      if (path.endsWith(".lua")) icon = "🔧";
      else if (path.endsWith(".vim")) icon = "⚙️";
      else if (path.endsWith(".md")) icon = "📝";
      html += `<div class="list-group-item list-group-item-action bg-dark text-light ${isActive}" data-path="${path}">
                        <span>${icon}</span> ${path}
                    </div>`;
    });
    fileListEl.innerHTML = html;

    fileListEl.querySelectorAll(".list-group-item").forEach((el) => {
      el.addEventListener("click", function () {
        const path = this.dataset.path;
        if (path) selectFile(path);
      });
    });
  }

  // ---------- Seleziona e mostra file ----------
  function selectFile(path) {
    if (!currentFiles || !currentFiles[path]) return;
    currentSelectedPath = path;

    fileListEl.querySelectorAll(".list-group-item").forEach((el) => {
      el.classList.toggle("active", el.dataset.path === path);
    });

    const content = currentFiles[path];
    const badge = `<div class="d-flex justify-content-between text-secondary small border-bottom border-secondary pb-1 mb-2">
                        <span>📁 ${path}</span>
                        <span>${content.length} caratteri</span>
                    </div>`;
    fileContentEl.innerHTML = badge + `<pre>${escapeHtml(content)}</pre>`;
  }

  // ---------- Escape HTML ----------
  function escapeHtml(text) {
    const div = document.createElement("div");
    div.textContent = text;
    return div.innerHTML;
  }

  // ---------- Scarica ZIP ----------
  async function downloadZip() {
    if (!currentFiles || Object.keys(currentFiles).length === 0) {
      showStatus("Nessun file da impacchettare", "warning");
      return;
    }
    hideStatus();
    downloadZipBtn.disabled = true;
    downloadZipBtn.innerHTML =
      '<span class="spinner-border spinner-border-sm me-1"></span> Creazione ZIP...';

    try {
      const zip = new JSZip();
      for (const [path, content] of Object.entries(currentFiles)) {
        zip.file(path, content);
      }
      const blob = await zip.generateAsync({ type: "blob" });
      const url = URL.createObjectURL(blob);
      const a = document.createElement("a");
      a.href = url;
      a.download = `nvim_config_${new Date().toISOString().slice(0, 19).replace(/[:-]/g, "")}.zip`;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
      showStatus("✅ ZIP scaricato con successo", "success");
    } catch (err) {
      showStatus(`❌ Errore: ${err.message}`, "danger");
    }

    downloadZipBtn.disabled = false;
    downloadZipBtn.innerHTML = "📦 Scarica ZIP";
  }

  // ---------- Init ----------
  generateBtn.addEventListener("click", generateConfig);
  downloadZipBtn.addEventListener("click", downloadZip);

  // Generazione automatica all'avvio per mostrare subito la struttura
  generateConfig();
})();
